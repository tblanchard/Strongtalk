extern "C" blockClosureOop allocateBlock0();
extern "C" blockClosureOop allocateBlock1();
extern "C" blockClosureOop allocateBlock2();
extern "C" blockClosureOop allocateBlock(smiOop nof);
extern "C" contextOop allocateContext(smiOop nofVars);

// push_new_closure_{context,tos}_{0,1,2,n}
void PortableInterpreter::push_closure(bool use_context, int nof_args) {
  int     lead = nof_args < 0 ? 2 : 1;		// _n variants have the number of arguments in the 2nd byte
  if (nof_args < 0) nof_args = hp[1];
  u_char* next = after_words(lead, 1);
  enter_C(next);
  blockClosureOop blk;
  switch (nof_args) {
    case 0:  blk = allocateBlock0(); break;
    case 1:  blk = allocateBlock1(); break;
    case 2:  blk = allocateBlock2(); break;
    default: blk = allocateBlock(as_smiOop(nof_args)); break;
  }
  leave_C();
  methodOop block_method = methodOop(*(oop*) (hp - oopSize));	// hp is the next instruction
  oop ctx = use_context ? temp(0) : pop();
  blk->set_method(block_method);
  blk->set_lexical_scope(contextOop(ctx));
  // increment the invocation counter of the enclosing method
  methodOop parent = methodOop(block_method->selector_or_method());
  int count = parent->invocation_count();
  if (count < methodOopDesc::_invocation_count_max) parent->set_invocation_count(count + 1);
  push(blk);
}

// install_new_context_{method,block}_n: allocates a context; its parent is the frame
// (method contexts) or the incoming context (block contexts).
void PortableInterpreter::install_context(int nof_vars, bool for_method) {
  u_char* next = hp + (nof_vars < 0 ? 2 : 1);
  if (nof_vars < 0) nof_vars = hp[1];
  enter_C(next);
  contextOop con = allocateContext(as_smiOop(nof_vars));
  leave_C();
  if (for_method) con->set_parent(oop(fp));	// the frame pointer looks like a smi
  else            con->set_parent(temp(0));
  temp(0) = con;
}

contextOop PortableInterpreter::context_at_depth(int depth) {
  contextOop c = context();
  for (int i = 0; i < depth; i++) c = contextOop(c->parent());
  return c;
}

// stores into a context variable (with store check)
static inline void context_store(contextOop c, int i, oop value) {
  Universe::store((oop*) memOop(c)->addr() + contextOopDesc::header_size() + i, value);
}

// copy_{self_}{1,2,n}_into_context: copy parameters (and self) into the context in temp0
void PortableInterpreter::copy_into_context(int n, bool with_self, u_char* indices) {
  contextOop con = context();
  int var = 0;
  if (with_self) context_store(con, var++, receiver());
  for (int i = 0; i < n; i++) context_store(con, var++, param(indices[i]));
}

void PortableInterpreter::zap_context() {
  contextOop con = context();
  con->set_parent(oop(NULL));
}

// ---------------------------------------------------------------------------
// Non-local returns

// non_local_return_{tos,self}_pop_n: find the home frame by following the context chain
bool PortableInterpreter::non_local_return(oop result, int nof_args) {
  contextOop last = context();
  oop home = last->parent();
  while (home->is_mem()) {
    last = contextOop(home);
    home = last->parent();
  }
  if (home == NULL) {
    // home frame has already returned
    push(result);
    error(nonlocal_return_error, hp + 2);
    return true;
  }
  nlr_home_context = last;
  return nlr_unwind(result, (intptr_t) home, ~nof_args);
}

// Unwinds frames until the home frame (home_fp) is found, zapping method contexts on the way.
// home_id is the ones complement of the number of arguments the home frame pops.
bool PortableInterpreter::nlr_unwind(oop result, intptr_t home_fp, int home_id) {
  have_nlr_through_C = false;
  while (true) {
    // zap the context of a method frame
    oop c = temp(0);
    if (c->is_mem() && c->klass() == contextKlassObj && contextOop(c)->parent() == oop(fp)) {
      contextOop(c)->set_parent(oop(NULL));
    }
    if ((intptr_t) fp == home_fp) {
      return return_from_frame(result, ~home_id);
    }
    char* ret_pc = frame_return_pc();
    intptr_t* link = frame_link();
    if (is_compiled_code_return(ret_pc)) {
      // the caller is compiled code: continue the NLR at the NLR target of its send
      // (as continue_NLR: the frame and the return address are removed, the arguments not)
      _to_compiled  = returned_with_nlr;
      _continuation = ic_info_at(ret_pc)->NLR_target();
      nlr_result  = result;
      nlr_home    = home_fp;
      nlr_home_id = home_id;
      sp = (oop*) (fp + frame_sender_sp_offset);
      fp = link;
      _result = result;
      return false;
    }
    if (ret_pc == (char*) &return_from_Delta) {
      // leaving this interpreter activation (back to C): continue the NLR there
      have_nlr_through_C = true;
      nlr_result  = result;
      nlr_home    = home_fp;
      nlr_home_id = home_id;
      sp = (oop*) (fp + frame_sender_sp_offset);
      fp = link;
      _result = result;
      return false;
    }
    sp = (oop*) (fp + frame_sender_sp_offset);
    fp = link;
  }
}

// ---------------------------------------------------------------------------
// Errors, control structures

void PortableInterpreter::error(InterpreterErrorConstants code, u_char* next) {
  enter_C(next);
  suspend_on_error(code);
  leave_C();
}

// if/and/or (byte and word forms); returns false if returning to C.
bool PortableInterpreter::conditional(bool cond, bool is_if, bool word) {
  oop     c    = tos();
  oop     want = cond ? trueObj : falseObj;
  oop     other= cond ? falseObj : trueObj;
  u_char* next;
  intptr_t offset;
  if (is_if) {
    next   = word ? after_words(2, 1) : hp + 3;
    offset = word ? long_operand(2) : hp[2];
  } else {
    next   = word ? after_words(1, 1) : hp + 2;
    offset = word ? long_operand(1) : hp[1];
  }
  if (c == want) {
    // take the inline branch; if: discard the condition, and/or: the condition is discarded too
    sp++;
    hp = next;
    return true;
  }
  if (c != other) {
    error(boolean_expected, next);
    return true;
  }
  // skip: if discards the condition; and/or keep it as the result
  if (is_if) sp++;
  hp = next + offset;
  return true;
}

bool PortableInterpreter::while_loop(bool cond, bool word) {
  oop     c      = tos();
  intptr_t offset = word ? long_operand(1) : hp[1];
  u_char* next   = word ? after_words(1, 1) : hp + 2;
  if (c == (cond ? trueObj : falseObj)) {
    sp++;
    hp -= offset;			// backwards jump relative to this instruction
    if (++interpreter_loop_counter > interpreter_loop_counter_limit && interpreter_loop_counter_limit > 0) {
      interpreter_loop_counter = 0;
    }
    return true;
  }
  if (c != (cond ? falseObj : trueObj)) {
    error(boolean_expected, next);
    return true;
  }
  sp++;
  hp = next;
  return true;
}

// ---------------------------------------------------------------------------
// Floats

static void float_function(int f, double* x) {
  // x[0] = float(i), x[-1*slot] = float(i+1)
  double* y = (double*) ((char*) x - floatSlotSize);
  switch (f) {
    case Floats::zero:     *x = 0.0;  break;
    case Floats::one:      *x = 1.0;  break;
    case Floats::abs:      *x = fabs(*x); break;
    case Floats::negated:  *x = -*x; break;
    case Floats::squared:  *x = *x * *x; break;
    case Floats::sqrt:     *x = ::sqrt(*x); break;
    case Floats::sin:      *x = ::sin(*x); break;
    case Floats::cos:      *x = ::cos(*x); break;
    case Floats::tan:      *x = ::tan(*x); break;
    case Floats::exp:      *x = ::exp(*x); break;
    case Floats::ln:       *x = ::log(*x); break;
    case Floats::add:      *x = *x + *y; break;
    case Floats::subtract: *x = *x - *y; break;
    case Floats::multiply: *x = *x * *y; break;
    case Floats::divide:   *x = *x / *y; break;
    case Floats::modulo:   *x = fmod(*x, *y); break;
    default: fatal1("illegal float function %d", f);
  }
}

static oop float_function_to_oop(int f, double* x) {
  double* y = (double*) ((char*) x - floatSlotSize);
  switch (f) {
    case Floats::is_zero:          return *x == 0.0 ? trueObj : falseObj;
    case Floats::is_not_zero:      return *x != 0.0 ? trueObj : falseObj;
    case Floats::is_equal:         return *x == *y ? trueObj : falseObj;
    case Floats::is_not_equal:     return *x != *y ? trueObj : falseObj;
    case Floats::is_less:          return *x <  *y ? trueObj : falseObj;
    case Floats::is_less_equal:    return *x <= *y ? trueObj : falseObj;
    case Floats::is_greater:       return *x >  *y ? trueObj : falseObj;
    case Floats::is_greater_equal: return *x >= *y ? trueObj : falseObj;
    default: fatal1("illegal float function %d", f); return NULL;
  }
}

// float_{nullary,unary,binary}_op[_to_oop] <float no> <function>
void PortableInterpreter::float_op(int nof_args, bool returns_float) {
  int     no = hp[1];
  double* x  = float_addr(no);
  int     f  = hp[2];
  u_char* next = hp + 3;
  if (returns_float) {
    float_function(f, x);
  } else if (f == Floats::oopify) {
    enter_C(next);
    oop result = oopFactory::new_double(*float_addr(no));
    leave_C();
    push(result);
    return;			// hp is the next instruction
  } else {
    push(float_function_to_oop(f, x));
  }
  hp = next;
}

