// Primitives

oop PortableInterpreter::invoke_primitive(fntype fn, int n, oop* a) {
  // PRIM_DECL_n functions take their arguments in reverse order: the top of stack first
  typedef oop (*f0)();
  typedef oop (*f1)(oop);
  typedef oop (*f2)(oop, oop);
  typedef oop (*f3)(oop, oop, oop);
  typedef oop (*f4)(oop, oop, oop, oop);
  typedef oop (*f5)(oop, oop, oop, oop, oop);
  typedef oop (*f6)(oop, oop, oop, oop, oop, oop);
  typedef oop (*f7)(oop, oop, oop, oop, oop, oop, oop);
  typedef oop (*f8)(oop, oop, oop, oop, oop, oop, oop, oop);
  typedef oop (*f9)(oop, oop, oop, oop, oop, oop, oop, oop, oop);
  typedef oop (*f10)(oop, oop, oop, oop, oop, oop, oop, oop, oop, oop);
  switch (n) {
    case 0:  return ((f0)  fn)();
    case 1:  return ((f1)  fn)(a[0]);
    case 2:  return ((f2)  fn)(a[0], a[1]);
    case 3:  return ((f3)  fn)(a[0], a[1], a[2]);
    case 4:  return ((f4)  fn)(a[0], a[1], a[2], a[3]);
    case 5:  return ((f5)  fn)(a[0], a[1], a[2], a[3], a[4]);
    case 6:  return ((f6)  fn)(a[0], a[1], a[2], a[3], a[4], a[5]);
    case 7:  return ((f7)  fn)(a[0], a[1], a[2], a[3], a[4], a[5], a[6]);
    case 8:  return ((f8)  fn)(a[0], a[1], a[2], a[3], a[4], a[5], a[6], a[7]);
    case 9:  return ((f9)  fn)(a[0], a[1], a[2], a[3], a[4], a[5], a[6], a[7], a[8]);
    case 10: return ((f10) fn)(a[0], a[1], a[2], a[3], a[4], a[5], a[6], a[7], a[8], a[9]);
    default: fatal1("primitive with %d arguments not supported", n); return NULL;
  }
}

// Calls a DLL function with n word sized arguments. Extra arguments are harmless for C
// functions taking fewer (the arm64 / x86_64 calling conventions are caller cleanup).
intptr_t PortableInterpreter::invoke_dll(dll_func f, int n, intptr_t* a) {
  typedef intptr_t (*fn16)(intptr_t, intptr_t, intptr_t, intptr_t, intptr_t, intptr_t, intptr_t, intptr_t,
                           intptr_t, intptr_t, intptr_t, intptr_t, intptr_t, intptr_t, intptr_t, intptr_t);
  intptr_t b[max_dll_arguments] = { 0 };
  for (int i = 0; i < n; i++) b[i] = a[i];
  return ((fn16) f)(b[0], b[1], b[2], b[3], b[4], b[5], b[6], b[7], b[8], b[9], b[10], b[11], b[12], b[13], b[14], b[15]);
}

// Number of arguments (incl. receiver) of a primitive, cached by function address.
int PortableInterpreter::primitive_arity(fntype fn) {
  const int size = 1024;
  static fntype keys[size];
  static int    values[size];
  int i = (int) (((uintptr_t) fn >> 3) % size);
  for (int probe = 0; probe < size; probe++, i = (i + 1) % size) {
    if (keys[i] == fn) return values[i];
    if (keys[i] == NULL) {
      primitive_desc* pdesc = primitives::lookup(fn);
      if (pdesc == NULL) fatal("primitive not in primitive table");
      values[i] = pdesc->number_of_parameters();
      keys[i]   = fn;
      return values[i];
    }
  }
  return primitives::lookup(fn)->number_of_parameters();
}

extern "C" oop primitiveValue0(oop);
extern "C" oop primitiveValue1(oop, oop);
extern "C" oop primitiveValue2(oop, oop, oop);
extern "C" oop primitiveValue3(oop, oop, oop, oop);
extern "C" oop primitiveValue4(oop, oop, oop, oop, oop);
extern "C" oop primitiveValue5(oop, oop, oop, oop, oop, oop);
extern "C" oop primitiveValue6(oop, oop, oop, oop, oop, oop, oop);
extern "C" oop primitiveValue7(oop, oop, oop, oop, oop, oop, oop, oop);
extern "C" oop primitiveValue8(oop, oop, oop, oop, oop, oop, oop, oop, oop);
extern "C" oop primitiveValue9(oop, oop, oop, oop, oop, oop, oop, oop, oop, oop);

static int primitive_value_arguments(fntype fn) {
  if (fn == (fntype) &primitiveValue0) return 0;
  if (fn == (fntype) &primitiveValue1) return 1;
  if (fn == (fntype) &primitiveValue2) return 2;
  if (fn == (fntype) &primitiveValue3) return 3;
  if (fn == (fntype) &primitiveValue4) return 4;
  if (fn == (fntype) &primitiveValue5) return 5;
  if (fn == (fntype) &primitiveValue6) return 6;
  if (fn == (fntype) &primitiveValue7) return 7;
  if (fn == (fntype) &primitiveValue8) return 8;
  if (fn == (fntype) &primitiveValue9) return 9;
  return -1;
}

// prim_call / prim_call_self (BL: fn) and prim_call_failure / prim_call_self_failure (BLL: fn, offset)
bool PortableInterpreter::call_primitive(bool can_fail) {
  fntype   fn   = (fntype) long_operand(1);
  u_char*  next = after_words(1, can_fail ? 2 : 1);

  int value_args = primitive_value_arguments(fn);
  if (value_args >= 0) {
    hp = next;
    return primitive_value(value_args, can_fail);
  }

  int n = primitive_arity(fn);
  enter_C(next);
  oop result = invoke_primitive(fn, n, sp);
  leave_C();
  if (have_nlr_through_C) return nlr_unwind(nlr_result, nlr_home, nlr_home_id);
  sp += n;			// the callee pops its arguments
  if (!can_fail) {
    assert(!result->is_mark(), "primitive failed that is not supposed to fail");
    push(result);
  } else if (result->is_mark()) {
    push(oop((intptr_t) result & ~(intptr_t) Mark_Tag_Bit));	// unmark the error and execute the failure block
  } else {
    push(result);
    hp += *(intptr_t*) (hp - oopSize);	// jump over the failure block
  }
  return true;
}

// Block evaluation (primitiveValue0..9): the block frame is activated on top of the
// primitive's arguments (block, arg1 ... argN) as in the x86 interpreter.
bool PortableInterpreter::primitive_value(int nof_args, bool can_fail) {
  blockClosureOop blk = blockClosureOop(sp[nof_args]);
  saved_hp() = hp;
  if (blk->isCompiledBlock()) {
    // compiled block: eax = the closure; it pops its arguments and the closure
    return call_compiled(blk->jump_table_entry()->entry_point(), blk, can_fail ? rp_primitive_can_fail : rp_primitive);
  }
  methodOop m = blk->method();
  contextOop ctx = blk->lexical_scope();
  activate(m, ctx, ctx, can_fail ? rp_primitive_can_fail : rp_primitive);
  return true;
}

// dll_call_{sync,async}: [code] *[dll name] [function name] [entry point] [no. of args]
// Stack: [... result proxy, arg 1, ..., arg n]. Smi arguments are passed as integers, proxies
// as their pointers (cf. StubRoutines::generate_call_DLL); the result is boxed into the proxy.
void PortableInterpreter::call_dll(bool async) {
  u_char*  nargs_addr = after_words(1, 3);
  int      n          = *nargs_addr;
  u_char*  next       = nargs_addr + 1;
  dll_func f          = (dll_func) *(intptr_t*) (nargs_addr - oopSize);
  if (n > max_dll_arguments) fatal1("DLL call with %d arguments not supported", n);

  if (f == NULL) {
    // first call: look up the function and patch the DLL cache
    enter_C(next);
    f = DLLs::lookup_and_patch_InterpretedDLL_Cache();
    leave_C();
    if (have_nlr_through_C) return;		// continued by the interpreter loop
    if (f == NULL) fatal("DLL function lookup failed");
  }

  intptr_t a[max_dll_arguments];
  for (int i = 0; i < n; i++) {
    oop x = sp[n - 1 - i];				// argument i+1
    a[i] = x->is_smi() ? smiOop(x)->value() : (intptr_t) proxyOop(x)->get_pointer();
  }

  enter_C(next);
  DeltaProcess* state = NULL;
  if (async) DLLs::enter_async_call(&state);
  intptr_t result = invoke_dll(f, n, a);
  if (async) DLLs::exit_async_call(&state);
  else       DLLs::exit_sync_call(&state);
  leave_C();

  sp += n;						// pop the arguments
  proxyOop(tos())->set_pointer((void*) result);		// box the result in the proxy (tos)
}

