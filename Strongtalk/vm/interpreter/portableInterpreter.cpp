// ---------------------------------------------------------------------------
// The interpreter

class PortableInterpreter {
 private:
  intptr_t* fp;
  oop*      sp;
  u_char*   hp;
  oop       _result;		// result when returning to C
  DeltaStack* _stack;
  intptr_t  _to_compiled;	// -1, or how the activation leaves to compiled code (returned_normally/returned_with_nlr)
  char*     _continuation;	// where compiled code continues

  // frame access
  oop&     receiver()          { return ((oop*) fp)[frame_receiver_offset]; }
  oop&     temp(int i)         { return ((oop*) fp)[frame_temp_offset - i]; }
  oop&     arg(int i)          { return ((oop*) fp)[frame_arg_offset - 1 + i]; }	// arg_1 = last pushed
  oop&     param(int i)        { return ((oop*) fp)[frame_arg_offset + i]; }	// param 0 = last pushed
  u_char*& saved_hp()          { return *(u_char**) &((oop*) fp)[frame_hp_offset]; }
  char*    frame_return_pc()   { return ((char**) fp)[frame_return_addr_offset]; }
  intptr_t* frame_link()       { return ((intptr_t**) fp)[frame_link_offset]; }
  contextOop context()         { return contextOop(temp(0)); }

  // expression stack
  void push(oop v)             { *--sp = v; }
  oop  pop()                   { return *sp++; }
  oop& tos()                   { return sp[0]; }

  // byte code operands
  static u_char* align(u_char* p) { return (u_char*) roundTo((uintptr_t) p, (uintptr_t) oopSize); }
  oop*      oop_operand(int offset)  { return (oop*) align(hp + offset); }	// aligned word after offset bytes
  intptr_t  long_operand(int offset) { return *(intptr_t*) align(hp + offset); }
  u_char*   after_words(int offset, int n) { return align(hp + offset) + n * oopSize; }

  // C call-outs (cf. call_C in interpreter.cpp): the frame must be walkable while in C
  void enter_C(u_char* hp_to_save) {
    saved_hp()    = hp_to_save;
    sp[-1]        = (oop) return_pc(rp_c_call);
    last_Delta_fp = fp;
    last_Delta_sp = sp;
  }
  // After a call-out hp is the saved hp: usually the next instruction (possibly adjusted by a
  // GC that moved the method), or what C set it to (inline cache misses, primitive lookup).
  // Operands of the current instruction must be read relative to it (trailing words).
  void leave_C() {
    last_Delta_fp = NULL;
    hp = saved_hp();
  }

  void check_stack(int words) {
    if (sp - words - delta_stack_slack < _stack->low) {
      fatal("Delta stack overflow (deep recursion?)");
    }
  }

  // activation & return
  void activate(methodOop m, oop recv, oop temp0, ReturnPoint rp);
  void activate_from_entry(methodOop m, oop recv, oop temp0);
  bool return_from_frame(oop result, int nof_args);	// false if returning to C
  bool continue_caller(char* ret_pc, oop result);	// false if returning to C

  // instructions
  bool send(Bytecodes::Code code);			// false if returning to C
  bool smi_predicted_send(Bytecodes::Code code);
  bool call_primitive(bool can_fail);
  bool primitive_value(int nof_args, bool can_fail);
  void call_dll(bool async);
  void push_closure(bool use_context, int nof_args_or_minus);
  void install_context(int nof_vars, bool for_method);
  void copy_into_context(int n, bool with_self, u_char* indices);
  contextOop context_at_depth(int depth);
  bool non_local_return(oop result, int nof_args);
  bool nlr_unwind(oop result, intptr_t home, int home_id);
  void zap_context();
  void error(InterpreterErrorConstants code, u_char* next);
  bool conditional(bool cond, bool is_if, bool word);
  bool while_loop(bool cond, bool word);
  void float_op(int nof_args, bool returns_float);
  double* float_addr(int no) {
    // floats are numbered max_nof_floats-1 .. 0 starting right below temp1 (see InterpreterGenerator)
    return (double*) ((char*) fp + oopSize * (frame_temp_offset - 3) - (255 - no) * floatSlotSize);
  }
  void trace_bytecode();

  static oop invoke_primitive(fntype fn, int nof_args, oop* args);
  enum { max_dll_arguments = 16 };
  static intptr_t invoke_dll(dll_func f, int n, intptr_t* a);
  static int primitive_arity(fntype fn);

 public:
  // Runs until the frame activated from the entry frame returns. Returns false if
  // an NLR is leaving the activation (have_nlr_through_C is set).
  bool run();
  oop  result() const { return _result; }

  PortableInterpreter(intptr_t* f, oop* s, DeltaStack* st) : fp(f), sp(s), hp(NULL), _result(NULL), _stack(st), _to_compiled(-1), _continuation(NULL) {}

  // compiled code
  bool call_compiled(char* entry, oop recv, ReturnPoint rp);	// false if returning to C
  void activate_from_compiled(methodOop m, oop recv, oop temp0);
  void count_invocation(methodOop m);

  friend oop call_delta_entry(methodOop m, oop receiver, int nof_args, oop* args, bool is_block);
  friend oop call_compiled_from_C(char* entry, oop receiver, int nof_args, oop* args, bool is_block);
  friend void interpret_from_compiled_activation(methodOop m, oop receiver, oop temp0, oop* sp, intptr_t* fp, CompiledReturn* out);
};

// ---------------------------------------------------------------------------
// Activation & return

void PortableInterpreter::activate(methodOop m, oop recv, oop temp0, ReturnPoint rp) {
  check_stack(8);
  push((oop) return_pc(rp));
  push((oop) fp);
  fp = (intptr_t*) sp;
  push(recv);
  push((oop) m->codes());
  push(temp0);
  hp = m->codes();
  count_invocation(m);
}

void PortableInterpreter::activate_from_entry(methodOop m, oop recv, oop temp0) {
  check_stack(8);
  push((oop) &return_from_Delta);
  push((oop) fp);
  fp = (intptr_t*) sp;
  push(recv);
  push((oop) m->codes());
  push(temp0);
  hp = m->codes();
  count_invocation(m);
}

// Calls compiled code (eax = recv; the arguments are on the stack, the callee pops them).
// The return pc of the callee is the return point rp; saved_hp() must be set.
bool PortableInterpreter::call_compiled(char* entry, oop recv, ReturnPoint rp) {
  check_stack(8);
  CompiledReturn r;
  delta_call_compiled(entry, recv, sp, fp, return_pc(rp), &r);
  assert(r.fp == fp, "compiled code returned to another frame");
  if (r.kind == returned_with_nlr) {
    // the NLR continues in this frame (the callee's arguments are still on the stack)
    return nlr_unwind(r.result, r.home, (int) r.home_id);
  }
  sp = r.sp;						// the callee popped its arguments
  return continue_caller(return_pc(rp), r.result);
}

// The frame of a method called from compiled code: the return address is already on the stack.
void PortableInterpreter::activate_from_compiled(methodOop m, oop recv, oop temp0) {
  check_stack(8);
  push((oop) fp);
  fp = (intptr_t*) sp;
  push(recv);
  push((oop) m->codes());
  push(temp0);
  hp = m->codes();
  count_invocation(m);
}

// Counts the invocation of the method of the (complete) current frame; at the limit the
// recompiler is called (cf. the x86 interpreter's method entry). Execution continues in
// the interpreter (the x86 interpreter ignores a new nmethod too).
void PortableInterpreter::count_invocation(methodOop m) {
  int count = m->invocation_count() + 1;
  if (count > methodOopDesc::_invocation_count_max) return;
  m->set_invocation_count(count);
  if (UseArm64Compiler && UseRecompilation && count >= Interpreter::get_invocation_counter_limit()) {
    enter_C(hp);
    Recompilation::methodOop_invocation_counter_overflow(receiver(), m);
    leave_C();			// hp: the method may have been moved
  }
}

// Removes the current frame and nof_args arguments; continues the caller.
bool PortableInterpreter::return_from_frame(oop result, int nof_args) {
  char* ret_pc = frame_return_pc();
  intptr_t* link = frame_link();
  sp = (oop*) (fp + frame_sender_sp_offset) + nof_args;
  fp = link;
  return continue_caller(ret_pc, result);
}

bool PortableInterpreter::continue_caller(char* ret_pc, oop result) {
  if (ret_pc == (char*) &return_from_Delta) {
    have_nlr_through_C = false;		// normal return to C
    _result = result;
    return false;
  }
  if (is_compiled_code_return(ret_pc)) {
    // the frame was called by compiled code (interpret_from_compiled): continue there
    _to_compiled   = returned_normally;
    _continuation  = ret_pc;
    _result        = result;
    return false;
  }
  hp = saved_hp();
  switch (return_point_of(ret_pc)) {
    case rp_send_with_receiver:		sp++; push(result); break;
    case rp_send_with_receiver_pop:	sp++;               break;
    case rp_send_without_receiver:	push(result);       break;
    case rp_send_without_receiver_pop:	                    break;
    case rp_primitive:			push(result);       break;
    case rp_primitive_can_fail:
      // a block evaluated by a primitive does not fail: jump over the failure block
      push(result);
      hp += *(intptr_t*) (hp - oopSize);
      break;
    default: fatal("illegal interpreter return point");
  }
  return true;
}

// ---------------------------------------------------------------------------
// Sends

bool PortableInterpreter::send(Bytecodes::Code code) {
  Bytecodes::ArgumentSpec spec = Bytecodes::argument_spec(code);
  int lead = 1, nof_args;
  switch (spec) {
    case Bytecodes::recv_0_args: nof_args = 0; break;
    case Bytecodes::recv_1_args: nof_args = 1; break;
    case Bytecodes::recv_2_args: nof_args = 2; break;
    case Bytecodes::recv_n_args: nof_args = hp[1]; lead = 2; break;
    case Bytecodes::args_only:   nof_args = as_InterpretedIC((char*) after_words(lead, 2))->nof_arguments(); break;
    default: ShouldNotReachHere(); nof_args = 0;
  }
  bool with_receiver = spec != Bytecodes::args_only;
  oop* ic   = oop_operand(lead);
  u_char* next = after_words(lead, 2);
  oop recv  = with_receiver ? sp[nof_args] : receiver();
  klassOop klass = recv->klass();

  // the target: an interpreted method (m) or compiled code (a jump table entry point,
  // stored in inline caches as a smi-looking word)
  methodOop m = NULL;
  char* compiled_entry = NULL;
  switch (Bytecodes::send_type(code)) {
    case Bytecodes::polymorphic_send: {
      objArrayOop pic = objArrayOop(ic[1]);
      for (int i = pic->length() / 2; i > 0; i--) {
        if (pic->obj_at(2 * i) == klass) {
          oop entry = pic->obj_at(2 * i - 1);
          if (entry->is_mem() && entry->is_method()) m = methodOop(entry);
          else if (entry->is_smi())                    compiled_entry = (char*) entry;
          break;
        }
      }
      break;
    }
    case Bytecodes::megamorphic_send:
      if (!Bytecodes::is_super_send(code)) {
        enter_C(next);
        LookupResult r = interpreter_normal_lookup(klass, symbolOop(ic[0]));
        leave_C();
        if (!r.is_empty() && r.is_method()) m = r.method();
        if (!r.is_empty() && r.is_entry())  compiled_entry = r.entry()->entry_point();
        // hp is the next instruction now; reload (a GC may have moved objects)
        next = hp;
        ic   = (oop*) (next - 2 * oopSize);
        recv = with_receiver ? sp[nof_args] : receiver();
        break;
      }
      // super sends use the inline cache (fall through)
    default:
      // interpreted, primitive, accessor, predicted and compiled sends: monomorphic inline cache
      if (ic[1] == klass) {
        if (ic[0]->is_mem() && ic[0]->is_method())                                    m = methodOop(ic[0]);
        else if (ic[0]->is_smi() && Bytecodes::send_type(code) == Bytecodes::compiled_send) compiled_entry = (char*) ic[0];
      }
      break;
  }

  if (compiled_entry != NULL) {
    saved_hp() = next;
    bool pop = Bytecodes::pop_tos(code);
    ReturnPoint rp = with_receiver ? (pop ? rp_send_with_receiver_pop    : rp_send_with_receiver)
                                   : (pop ? rp_send_without_receiver_pop : rp_send_without_receiver);
    return call_compiled(compiled_entry, recv, rp);
  }

  if (m == NULL) {
    // inline cache miss: updates the cache and resets the frame's hp to the send
    enter_C(next);
    InterpretedIC::inline_cache_miss();
    leave_C();
    if (have_nlr_through_C) return nlr_unwind(nlr_result, nlr_home, nlr_home_id);
    return true;
  }

  saved_hp() = next;
  bool pop = Bytecodes::pop_tos(code);
  ReturnPoint rp = with_receiver ? (pop ? rp_send_with_receiver_pop    : rp_send_with_receiver)
                                 : (pop ? rp_send_without_receiver_pop : rp_send_without_receiver);
  activate(m, recv, nilObj, rp);
  return true;
}

// Predicted smi sends (smi_add etc.): fall back to the send if the arguments are no smis.
bool PortableInterpreter::smi_predicted_send(Bytecodes::Code code) {
  oop a = sp[0];
  oop r = sp[1];
  if (r->is_smi() && a->is_smi()) {
    intptr_t x = (intptr_t) r, y = (intptr_t) a;	// tagged values (Int_Tag == 0)
    intptr_t v;
    oop result = NULL;
    switch (code) {
      case Bytecodes::smi_add:  if (!__builtin_add_overflow(x, y, &v)) result = oop(v); break;
      case Bytecodes::smi_sub:  if (!__builtin_sub_overflow(x, y, &v)) result = oop(v); break;
      case Bytecodes::smi_mult: if (!__builtin_mul_overflow(x, smiOop(a)->value(), &v)) result = oop(v); break;
      case Bytecodes::smi_equal:         result = x == y ? trueObj : falseObj; break;
      case Bytecodes::smi_not_equal:     result = x != y ? trueObj : falseObj; break;
      case Bytecodes::smi_less:          result = x <  y ? trueObj : falseObj; break;
      case Bytecodes::smi_less_equal:    result = x <= y ? trueObj : falseObj; break;
      case Bytecodes::smi_greater:       result = x >  y ? trueObj : falseObj; break;
      case Bytecodes::smi_greater_equal: result = x >= y ? trueObj : falseObj; break;
      case Bytecodes::smi_and: result = oop(x & y); break;
      case Bytecodes::smi_or:  result = oop(x | y); break;
      case Bytecodes::smi_xor: result = oop(x ^ y); break;
      case Bytecodes::smi_shift: {
        // overflow is ignored (as in the x86 interpreter); shift counts are taken mod BitsPerWord
        smi n = smiOop(a)->value();
        if (n >= 0) result = oop((uintptr_t) x << (n % BitsPerWord));
        else        result = oop((x >> ((-n) % BitsPerWord)) & ~(intptr_t) Tag_Mask);
        break;
      }
      default: break;	// smi_div, smi_mod, smi_create_point, objArray_*: always send
    }
    if (result != NULL) {
      sp++;
      tos() = result;
      hp = after_words(1, 2);
      return true;
    }
  }
  return send(code);
}

