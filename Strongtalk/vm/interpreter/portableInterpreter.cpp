// Portable (C++) byte code interpreter.
//
// Replaces the x86-32 interpreter (interpreter_asm.asm and the code generated by
// InterpreterGenerator) on hosts without the x86 backend. It keeps the original
// interpreter frame layout so that the rest of the VM (stack walking, GC, vframes,
// debugging, process switching) works unchanged:
//
//   Delta frames live on a per-thread "Delta stack" that grows downwards:
//
//     [expressions ...      ] <- sp
//     [temporaries ...      ]
//     [temp0                ]   fp[-3]  (context of the activation, if any)
//     [saved hp             ]   fp[-2]  (byte code pointer when calling out)
//     [receiver             ]   fp[-1]
//     [link (caller's fp)   ] <- fp
//     [return pc            ]   fp[1]
//     [last argument ...    ]   fp[2]   arg(i) = fp[1+i]
//
//   Frames are classified by their return pc (see frame.cpp): return pcs of
//   interpreted frames point into a small static area (interpreter_begin_addr ..
//   interpreter_end_addr); the offset encodes what the caller does after the
//   call. Entry frames (calls from C, see call_delta) have the return pc
//   &return_from_Delta and hold the previous last_Delta_fp/sp at fp[-1]/fp[-2].
//
//   The complete expression stack is always in memory (the x86 interpreter kept
//   the top of stack in eax, but pushed it at every call-out, so the memory
//   layouts at call-outs are the same).

