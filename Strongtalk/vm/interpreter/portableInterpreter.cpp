// Entry from C

// Calls method (or, if is_block, the block method of the closure receiver) with
// receiver and arguments. Builds an entry frame on the Delta stack (see frame.hpp,
// frame_next_Delta_fp_offset) and runs the interpreter until the method returns.
oop call_compiled_from_C(char* entry, oop receiver, int nof_args, oop* args, bool is_block);

oop call_delta_entry(methodOop m, oop receiver, int nof_args, oop* args, bool is_block) {
  if (is_block && blockClosureOop(receiver)->isCompiledBlock()) {
    return call_compiled_from_C(blockClosureOop(receiver)->jump_table_entry()->entry_point(), receiver, nof_args, args, true);
  }
  DeltaStack* stack = delta_stack();
  intptr_t* saved_fp = last_Delta_fp;
  oop*      saved_sp = last_Delta_sp;
  // nested calls continue below the calling Delta frame (keep its return pc at sp[-1])
  oop* sp = saved_fp != NULL ? saved_sp - 2 : stack->high;
  if (sp - delta_stack_slack < stack->low) fatal("Delta stack overflow");

  *--sp = NULL;					// return address of the entry frame (C)
  *--sp = NULL;					// link
  intptr_t* entry_fp = (intptr_t*) sp;
  *--sp = (oop) saved_fp;			// fp[-1]: next_Delta_fp
  *--sp = (oop) saved_sp;			// fp[-2]: next_Delta_sp
  last_Delta_fp = NULL;

  PortableInterpreter in(entry_fp, sp, stack);
  if (is_block) {
    // primitiveValueN called from C: the block and its arguments are the "primitive" arguments
    *--in.sp = receiver;
    for (int i = 0; i < nof_args; i++) *--in.sp = args[i];
    blockClosureOop blk = blockClosureOop(receiver);
    contextOop ctx = blk->lexical_scope();
    in.activate_from_entry(blk->method(), ctx, ctx);
  } else {
    for (int i = 0; i < nof_args; i++) *--in.sp = args[i];
    in.activate_from_entry(m, receiver, nilObj);
  }

  Activation act;
  act.previous = current_activation;
  act.entry_fp = entry_fp;
  current_activation = &act;

  if (setjmp(act.buf) != 0) {
    // provoke_nlr_at / continue_nlr_in_delta: resume the NLR in the given frame
    in.fp = act.resume_fp;
    in.sp = act.resume_sp;
    last_Delta_fp = NULL;
    if (in.nlr_unwind(nlr_result, nlr_home, nlr_home_id)) in.run();
  } else {
    in.run();
  }

  current_activation = act.previous;
  last_Delta_fp = saved_fp;
  last_Delta_sp = saved_sp;
  if (!have_nlr_through_C) return in.result();
  return nlr_result;
}

// Calls compiled code from C (call_delta with a jump table entry): as call_delta_entry, but
// the callee is compiled; it returns to return_from_Delta.
oop call_compiled_from_C(char* entry, oop receiver, int nof_args, oop* args, bool is_block) {
  DeltaStack* stack = delta_stack();
  intptr_t* saved_fp = last_Delta_fp;
  oop*      saved_sp = last_Delta_sp;
  oop* sp = saved_fp != NULL ? saved_sp - 2 : stack->high;
  if (sp - delta_stack_slack < stack->low) fatal("Delta stack overflow");

  *--sp = NULL;					// return address of the entry frame (C)
  *--sp = NULL;					// link
  intptr_t* entry_fp = (intptr_t*) sp;
  *--sp = (oop) saved_fp;			// fp[-1]: next_Delta_fp
  *--sp = (oop) saved_sp;			// fp[-2]: next_Delta_sp
  last_Delta_fp = NULL;
  if (is_block) *--sp = receiver;		// blocks pop the closure (the first argument of primitiveValue)
  for (int i = 0; i < nof_args; i++) *--sp = args[i];

  CompiledReturn r;
  delta_call_compiled(entry, receiver, sp, entry_fp, (char*) &return_from_Delta, &r);

  last_Delta_fp = saved_fp;
  last_Delta_sp = saved_sp;
  if (r.kind == returned_with_nlr) {
    // the NLR leaves the Delta code called from C
    have_nlr_through_C = true;
    nlr_result  = r.result;
    nlr_home    = r.home;
    nlr_home_id = (int) r.home_id;
    return nlr_result;
  }
  have_nlr_through_C = false;
  return r.result;
}

// Runs an interpreted method called from compiled code (see compiled_to_interpreted): sp points
// to the return address into compiled code, fp is the compiled caller's frame.
void interpret_from_compiled_activation(methodOop m, oop receiver, oop temp0, oop* sp, intptr_t* fp, CompiledReturn* out) {
  intptr_t* saved_fp = last_Delta_fp;
  oop*      saved_sp = last_Delta_sp;
  last_Delta_fp = NULL;

  PortableInterpreter in(fp, sp, delta_stack());
  in.activate_from_compiled(m, receiver, temp0);

  Activation act;
  act.previous = current_activation;
  act.entry_fp = (intptr_t*) sp;		// the frames of this activation are below the return address
  current_activation = &act;
  if (setjmp(act.buf) != 0) {
    in.fp = act.resume_fp;
    in.sp = act.resume_sp;
    last_Delta_fp = NULL;
    if (in.nlr_unwind(nlr_result, nlr_home, nlr_home_id)) in.run();
  } else {
    in.run();
  }
  current_activation = act.previous;
  last_Delta_fp = saved_fp;
  last_Delta_sp = saved_sp;

  if (in._to_compiled < 0) fatal("interpreted method called from compiled code does not return to it");
  out->result       = in._result;
  out->sp           = in.sp;
  out->fp           = in.fp;
  out->kind         = in._to_compiled;
  out->continuation = in._continuation;
  out->home         = nlr_home;
  out->home_id      = nlr_home_id;
}

extern "C" void interpret_from_compiled(methodOop m, oop receiver, oop* sp, intptr_t* fp, CompiledReturn* out) {
  interpret_from_compiled_activation(m, receiver, nilObj, sp, fp, out);
}

// restart_primitiveValue (portableInterpreter_arm64.S) for an interpreted block: the block
// method runs with the context as receiver and temp0 (cf. primitive_value)
extern "C" void interpret_block_from_compiled(blockClosureOop blk, oop* sp, intptr_t* fp, CompiledReturn* out) {
  contextOop ctx = blk->lexical_scope();
  interpret_from_compiled_activation(blk->method(), ctx, ctx, sp, fp, out);
}

extern "C" oop call_delta(void* method, oop receiver, int nofArgs, oop* args) {
  oop m = (oop) method;
  if (m->is_mem() && m->is_method()) return call_delta_entry(methodOop(m), receiver, nofArgs, args, false);
  // a jump table entry (compiled code)
  return call_compiled_from_C((char*) method, receiver, nofArgs, args, false);
}

// The method entry for compiled code (the PIC and megamorphic IC stubs jump to it)
static struct MethodEntryInit {
  MethodEntryInit() { method_entry_point = (char*) &compiled_to_interpreted; }
} method_entry_init;

// Unwinds the C frames above the Delta frame (fp, sp) and starts/continues the NLR
// described by nlr_result/nlr_home/nlr_home_id in that frame.
static void resume_nlr_in(intptr_t* fp, oop* sp) {
  Activation* a = current_activation;
  while (a != NULL && !(fp < a->entry_fp)) a = a->previous;
  if (a == NULL) fatal("no interpreter activation for NLR");
  current_activation = a;
  a->resume_fp = fp;
  a->resume_sp = sp;
  longjmp(a->buf, 1);
}

extern "C" void provoke_nlr_at(intptr_t* frame_pointer, oop* stack_pointer) {
  resume_nlr_in(frame_pointer, stack_pointer);
}

extern "C" void continue_nlr_in_delta(intptr_t* frame_pointer, oop* stack_pointer) {
  resume_nlr_in(frame_pointer, stack_pointer);
}

